/* sets interval to release a group of characters at the predetermined interval */
function countDownToGroupRelease() {
    var characterTimer = setInterval(() => {
        let now = new Date();
        let seconds = now.getSeconds();
        if (seconds % releaseDelay === 0) {
            releaseCount++;
            const isPowerUpRound = releaseCount % 5 === 0;
            releaseTheGroup(isPowerUpRound);
            clearInterval(characterTimer); // Clear interval to prevent multiple triggers
            setTimeout(() => {
                countDownToGroupRelease(); // Restart countdown for next release
            }, 1001);
        }
    }, 500);
}

/* animates a character moving across the top panel */
function animateCharacter(characterName="pac-man", direction="right", halfSpeed=true, mirror=false) {
    const characterData = getPixelDataByName(characterName);
    const frameCount = characterData.shape.length;
    const spriteWidth = characterData.shape[0].grid[0].length;
    let charFrame = 0;

    let pos;
    if (direction === "right") {
        pos = -spriteWidth + 1;
    } else if (direction === "left") {
        pos = xWidth;
    } else {
        pos = -spriteWidth + 1;
        direction = "right";
    }

    const characters = setInterval(() => {
        const isVisible = direction === "right" ? pos < xWidth : pos > -spriteWidth;

        if (!isVisible) {
            clearInterval(characters);
            return;
        }

        printCharToPanel(characterName, pos, "top", charFrame, mirror);
        pos += direction === "right" ? 1 : -1;

        if (charFrame < frameCount - 1) {
            charFrame += halfSpeed ? 0.5 : 1;
        } else {
            charFrame = 0;
        }
    }, characterSpeed);
}

/* releases a group of characters */
function releaseTheGroup(powerUp=false) {
    const characterReleaseDelay = characterSpeed * 20;
    const delayAfterGhostGroup = 600;

    if (powerUp) {
        const frightenedGhosts = [
            "ghost-frightened",
            "ghost-frightened",
            "ghost-frightened",
            "ghost-frightened"
        ];

        frightenedGhosts.forEach((ghostName, index) => {
            setTimeout(() => {
                animateCharacter(ghostName, "left", false, true);
            }, characterReleaseDelay * index);
        });

        setTimeout(() => {
            animateCharacter("pac-man", "left", true, true);
        }, characterReleaseDelay * frightenedGhosts.length + delayAfterGhostGroup);
        return;
    }

    const delayAfterPacMan = 600;
    animateCharacter("pac-man", "right", true);

    setTimeout(() => {
        animateCharacter("ghost-blinky", "right");
    }, characterReleaseDelay + delayAfterPacMan);

    setTimeout(() => {
        animateCharacter("ghost-pinky", "right");
    }, characterReleaseDelay * 2 + delayAfterPacMan);

    setTimeout(() => {
        animateCharacter("ghost-inky", "right");
    }, characterReleaseDelay * 3 + delayAfterPacMan);

    setTimeout(() => {
        animateCharacter("ghost-clyde", "right");
    }, characterReleaseDelay * 4 + delayAfterPacMan);
}

/* displays the current time in HH:MM format */
function displayTimeDigits(now = new Date()) {
    let hours = now.getHours().toString().padStart(2, '0');
    let minutes = now.getMinutes().toString().padStart(2, '0');

    const currentDigits = [
        hours.charAt(0),
        hours.charAt(1),
        minutes.charAt(0),
        minutes.charAt(1)
    ];

    const digitPlaces = [place1, place2, place4, place5];

    if (!previousTimeDigits) {
        currentDigits.forEach((digit, index) => {
            printCharToPanel(digit, digitPlaces[index], "bottom");
        });
        previousTimeDigits = currentDigits.slice();
        return;
    }

    currentDigits.forEach((digit, index) => {
        const place = digitPlaces[index];
        const previousDigit = previousTimeDigits[index];

        if (previousDigit !== digit) {
            animateDigitTransition(previousDigit, digit, place, "bottom", digitTransitionDuration, index);
        } else if (!activeDigitAnimations[index]) {
            printCharToPanel(digit, place, "bottom");
        }
    });

    previousTimeDigits = currentDigits.slice();
}

function animateDigitTransition(fromChar, toChar, digitPlace, panelName = "bottom", duration = 720, digitIndex = 0) {
    cancelDigitAnimation(digitIndex);

    const fromData = getPixelDataByName(fromChar);
    const toData = getPixelDataByName(toChar);

    if (!fromData || !toData || fromData.type !== "digit" || toData.type !== "digit") {
        printCharToPanel(toChar, digitPlace, panelName);
        return;
    }

    const fromShape = fromData.shape[0].grid;
    const toShape = toData.shape[0].grid;
    const rowCount = Math.max(fromShape.length, toShape.length);
    const stepDuration = Math.max(1, Math.round(duration / rowCount));
    const animationToken = Symbol(`digit-${digitIndex}-${Date.now()}`);

    activeDigitAnimations[digitIndex] = {
        token: animationToken,
        timeouts: []
    };

    for (let rowsFromTop = 1; rowsFromTop <= rowCount; rowsFromTop++) {
        const timeoutId = setTimeout(() => {
            const activeAnimation = activeDigitAnimations[digitIndex];
            if (!activeAnimation || activeAnimation.token !== animationToken) return;

            printDigitTransitionFrame(fromShape, toShape, digitPlace, panelName, rowsFromTop);

            if (rowsFromTop === rowCount) {
                delete activeDigitAnimations[digitIndex];
            }
        }, stepDuration * rowsFromTop);

        activeDigitAnimations[digitIndex].timeouts.push(timeoutId);
    }
}

function printDigitTransitionFrame(fromShape, toShape, digitPlace, panelName, rowsFromTop) {
    const rowCount = Math.max(fromShape.length, toShape.length);

    for (let y = 0; y < rowCount; y++) {
        const sourceShape = y < rowsFromTop ? toShape : fromShape;
        const row = sourceShape[y] || "00000000";
        renderPixelRow(row, digitPlace, panelName, y + yOffset);
    }
}

function renderPixelRow(rowString, digitPlace, panelName, targetY) {
    for (let x = 0; x < rowString.length; x++) {
        const pixelElement = document.getElementById(`${panelName}-${x + digitPlace}-${targetY}`);
        if (!pixelElement) continue;
        setPixelClass(pixelElement, rowString[x]);
    }
}

function cancelDigitAnimation(digitIndex) {
    const activeAnimation = activeDigitAnimations[digitIndex];
    if (!activeAnimation) return;

    activeAnimation.timeouts.forEach(timeoutId => clearTimeout(timeoutId));
    delete activeDigitAnimations[digitIndex];
}

function setPixelClass(pixelElement, pixelChar) {
    if (pixelChar === "0") {
        pixelElement.className = 'pixel pixel-blank';
    } else if (pixelChar === "1") {
        pixelElement.className = 'pixel pixel-white';
    } else if (pixelChar === "L") {
        pixelElement.className = 'pixel pixel-colon';
    } else if (pixelChar === "R") {
        pixelElement.className = 'pixel pixel-red';
    } else if (pixelChar === "P") {
        pixelElement.className = 'pixel pixel-pink';
    } else if (pixelChar === "C") {
        pixelElement.className = 'pixel pixel-cyan';
    } else if (pixelChar === "O") {
        pixelElement.className = 'pixel pixel-orange';
    } else if (pixelChar === "B") {
        pixelElement.className = 'pixel pixel-blue';
    } else if (pixelChar === "F") {
        pixelElement.className = 'pixel pixel-frightened';
    } else if (pixelChar === "Y") {
        pixelElement.className = 'pixel pixel-yellow';
    } else if (pixelChar === "W") {
        pixelElement.className = 'pixel pixel-white';
    } else {
        pixelElement.className = 'pixel pixel-blank';
    }
}

/* prints a static character to a specified panel at a specified position */
function printCharToPanel(charName, digitPlace, panelName, chosenFrame=0, mirror=false) {
    const digitData = getPixelDataByName(charName);
    const shape = digitData.shape[Math.floor(chosenFrame)].grid;

    for (let y = 0; y < shape.length; y++) {
        for (let x = 0; x < shape[y].length; x++) {
            const sourceX = mirror ? shape[y].length - 1 - x : x;
            const pixelChar = shape[y][sourceX];
            const startY = digitData.type === "digit" ? y + yOffset : y;
            const startX = x + digitPlace;

            try {
                const pixelElement = document.getElementById(`${panelName}-${startX}-${startY}`);
                if (!pixelElement) continue;
                setPixelClass(pixelElement, pixelChar);
            } catch (error) {
                // console.log("Pixel missing: " + `${panelName}: ${startX}-${startY}`);
            }
        }
    }
}

/* creates a pixel grid inside a specified container */
function createPixelGrid(container, name) {
    for (let y = 0; y < yHeight; y++) {
        let pixelRow = document.createElement('div');
        pixelRow.id = `${y+1}`;
        pixelRow.classList.add('pixel-row');
        for (let x = 0; x < xWidth; x++) {
            let pixel = document.createElement('div');
            pixel.classList.add('pixel');
            pixel.id = `${name}-${x}-${y}`;
            pixelRow.appendChild(pixel);
        }
        container.appendChild(pixelRow);
    }
}

/* retrieves pixel data using character name */
function getPixelDataByName(name) {
    for (let i = 0; i < pixelData.length; i++) {
        if (pixelData[i].name === name) {
            return pixelData[i];
        }
    }
    return null;
}

/* sets pixel height to match width for square pixels */
function getAndSetPixelSize() {
    const allPixels = document.querySelectorAll('.pixel');
    const pixel = document.querySelector('.pixel');
    const pixelWidth = pixel.offsetWidth;


    allPixels.forEach(div => {
        div.style.height = pixelWidth + "px";
    });
}

function updateFullscreenIcon() {
    const isFullscreen = !!document.fullscreenElement;
    fullscreenToggleInner.textContent = isFullscreen ? 'fullscreen_exit' : 'fullscreen';
    fullscreenButton.setAttribute('aria-pressed', isFullscreen ? 'true' : 'false');
}

/* Fullscreen toggle button functionality */
fullscreenButton.addEventListener('click', async () => {
    try {
        if (!document.fullscreenElement) {
            await document.documentElement.requestFullscreen();
        } else if (document.exitFullscreen) {
            await document.exitFullscreen();
        }
    } catch (error) {
        console.error('Fullscreen toggle failed:', error);
    } finally {
        updateFullscreenIcon();
    }
});

document.addEventListener('fullscreenchange', updateFullscreenIcon);
updateFullscreenIcon();





